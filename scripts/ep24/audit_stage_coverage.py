#!/usr/bin/env python3
"""Country x stage 0-9 coverage audit for EP24 (#306, deliverable 2).

    export LACLAUGPT_MONGODB_URI=...   # private environment, never echoed
    export LACLAUGPT_MONGODB_DATABASE=...
    python scripts/ep24/audit_stage_coverage.py --output <private-dir>/coverage.json --markdown coverage.md

Read-only. Emits counts and stage names only -- never row content, quotes, transcripts or ids.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

import ep24_coverage_audit as audit  # noqa: E402
import ep24_mongo_export as export  # noqa: E402
from ep24_stage_contract import STAGE_CONTRACT  # noqa: E402


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="EP24 country x stage coverage audit (#306).")
    parser.add_argument("--country", nargs="+", choices=export.COUNTRY_SLUGS,
                        default=list(export.COUNTRY_SLUGS))
    parser.add_argument("--output", required=True, type=Path, help="JSON report path")
    parser.add_argument("--markdown", type=Path, default=None, help="optional markdown report path")
    parser.add_argument("--record-unit", choices=export.RECORD_UNITS,
                        default=export.DEFAULT_RECORD_UNIT,
                        help="video (one row per media, default) or ingest (one per pipeline run)")
    parser.add_argument("--batch-size", type=int, default=1000)
    parser.add_argument("--timeout-ms", type=int, default=15000)
    return parser.parse_args(argv)


def dedupe(rows: list[dict[str, Any]], unit: str) -> list[dict[str, Any]]:
    """Collapse to one row per unit, keeping the row with the most populated audited columns.

    Percentages must be computed on the researcher's denominator. Auditing 3,700 ingest rows and
    calling the result a video coverage figure is how "73%" and "60%" end up describing one corpus.
    """
    if unit == "ingest":
        return rows
    groups: dict[str, list[dict[str, Any]]] = {}
    for row in rows:
        key = str(row.get("allas_filename") or "").strip() or str(row.get("_storage_id") or "").strip()
        if not key:
            key = f"row:{id(row)}"
        groups.setdefault(key, []).append(row)
    # Status, provenance and identity columns are not analysis outputs. A failed retry may
    # populate more bookkeeping columns than the successful run it followed.
    output_fields = {
        field for stage in STAGE_CONTRACT for field in stage.appends
        if not field.endswith(("_status", "_reason", "_error", "_model", "_version",
                               "_runtime_ms", "_generated_at", "_prompt_version",
                               "_context_sha256"))
    }

    def substantive_count(row: dict[str, Any]) -> int:
        return sum(not audit.empty_value(row.get(field)) for field in output_fields)

    kept = []
    for key in sorted(groups):
        candidates = groups[key]
        kept.append(max(candidates, key=lambda r: (
            substantive_count(r), str(r.get("_storage_id") or "")
        )))
    return kept


def render_markdown(report: dict[str, Any]) -> str:
    lines = [
        "# EP24 country x stage coverage (#306)",
        "",
        "Generated by `scripts/ep24/audit_stage_coverage.py` from the shared MongoDB frame.",
        "**Counts only** — no row content, quotes or identifiers are included.",
        "",
        "Three states are kept apart on purpose: *not started* (no output and no status), *failed* "
        "(the stage said so), and *claimed but empty* (the stage said success and produced nothing). "
        "The last one is invisible in any denominator built on `status = ok`.",
        "",
    ]
    for country, data in report["countries"].items():
        lines += [
            f"## {country.capitalize()}",
            "",
            f"Rows: **{data['rows']}** · distinct media keys: **{data['distinct_media']}** · "
            f"rows sharing a media key: **{data['rows_sharing_a_media_key']}**",
            "",
            "| stage | name | completed | not started | failed | other (reprocess/delete) | claimed but empty | coverage |",
            "|---:|---|---:|---:|---:|---:|---:|---:|",
        ]
        for stage in data["stages"]:
            if not stage.get("auditable", True):
                lines.append(f"| {stage['stage']} | {stage['name']} | — | — | — | — | not auditable |")
                continue
            other = stage.get("other_status", 0)
            other_detail = ", ".join(f"{k}={v}" for k, v in
                                     (stage.get("other_status_values") or {}).items())
            lines.append(
                f"| {stage['stage']} | {stage['name']} | {stage['completed']} | "
                f"{stage['not_started']} | {stage['failed']} | "
                f"{other}{f' ({other_detail})' if other_detail else ''} | "
                f"{stage['claimed_but_empty']} | {stage['coverage_pct']}% |"
            )
        lines += ["", f"ASR language values: `{json.dumps(data['asr_language'], sort_keys=True)}`", ""]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        uri, database = export.config_from_env()
    except export.ExportError as error:
        raise SystemExit(str(error)) from error

    from pymongo import MongoClient

    client = MongoClient(uri, serverSelectionTimeoutMS=args.timeout_ms)
    db = client[database]
    existing = set(db.list_collection_names())

    report: dict[str, Any] = {"read_only": True, "countries": {}}
    for country in args.country:
        source = export.collection_name(country, export.CANONICAL_SUFFIX)
        if source not in existing:
            raise SystemExit(f"collection missing for {country}: {source}")
        # Emptiness is decided in Mongo: each *output* column is reduced to 0/1 so transcripts and
        # context blobs never leave the server. Status columns stay verbatim -- their values are what
        # the four buckets are built from.
        status_names = {c for stage in STAGE_CONTRACT for c in stage.appends if c.endswith("_status")}
        # Identity and language fields must stay verbatim: reducing them to 0/1 would make every
        # media key identical (a "distinct media" count of 1) while leaving stage counts correct --
        # a silent wrong answer, which is worse than a loud one.
        verbatim = {"_storage_id", "allas_filename", "video_id", "country", "asr_language"}
        wanted = set(verbatim)
        for stage in STAGE_CONTRACT:
            wanted.update(stage.appends)
        projection: dict[str, Any] = {"_id": 0}
        for name in sorted(wanted):
            if name in verbatim or name in status_names:
                projection[name] = 1
                continue
            projection[name] = {
                "$cond": [
                    {"$in": [{"$ifNull": [f"${name}", None]}, [None, "", [], {}]]},
                    0,
                    1,
                ]
            }
        raw = db[source].aggregate([{"$project": projection}], batchSize=args.batch_size)
        # 0 means "no result"; hand the auditor None so it sees an empty value, not a zero result.
        rows = [{k: (None if v == 0 else v) for k, v in doc.items()} for doc in raw]
        rows = dedupe(rows, args.record_unit)
        report["countries"][country] = audit.audit_rows(rows, STAGE_CONTRACT)
        print(f"{country}: {len(rows)} rows audited")

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(report, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8"
    )
    if args.markdown:
        args.markdown.parent.mkdir(parents=True, exist_ok=True)
        args.markdown.write_text(render_markdown(report), encoding="utf-8")
        print(f"markdown -> {args.markdown}")
    print(f"json -> {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
