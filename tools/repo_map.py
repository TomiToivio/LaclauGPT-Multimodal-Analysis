    ("ep24_stage_state", "orchestration", "durable state: which stage has run for which record"),
    ("ep24_cli", "orchestration", "the shared command-line contract every numbered step uses"),
    ("ep24_scope", "orchestration", "decides which steps belong to the current run"),
    ("ep24_pipeline", "orchestration", "the dataframe contract shared by the active stage pipeline"),
    ("ep24_eligibility", "orchestration", "non-blocking eligibility rules for a stage"),
    ("roihu_preprocess", "stage: preprocessing", "Step 1 — OCR and speech recognition on the collected media"),
    ("roihu_frame", "stage: frame analysis", "Step 2 — single-keyframe multimodal analysis"),
    ("roihu_summary", "stage: summarisation", "Step 4 — multimodal social-semiotic summary and fusion"),
    ("roihu_postprocess", "stage: postprocessing", "Step 5 — structured postprocessing of the summary output"),
    ("roihu_populism", "stage: discourse coding", "Step 6 — Laclau/Palonen discourse coding"),
    ("step_7_", "stage: discourse network", "Step 7 — discourse network analysis (DNA)"),
    ("step_8_", "stage: social network", "Step 8 — evidence-backed social network analysis (SNA)"),
    ("step_9_", "stage: export", "Step 9 — deterministic RDF export"),
